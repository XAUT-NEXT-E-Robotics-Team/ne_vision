#pragma once

#include <tuple>
#include <utility>

namespace ne_vision
{

// 外部应用不要直接调用detail的东西j
namespace detail
{

// 遍历tuple
// 传入Func应该是[](auto){};
template <typename Tuple, typename Func>
inline void NeTraverseTuple(Tuple&& tuple, Func&& f)
{
  std::apply(
      [&](auto&&... elems) { (f(std::forward<decltype(elems)>(elems)), ...); },
      std::forward<Tuple>(tuple));
}

} // namespace detail

} // namespace ne_vision
